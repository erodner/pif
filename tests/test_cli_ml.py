from __future__ import annotations

import json
import shutil
from pathlib import Path

import pytest
from typer.testing import CliRunner

from pif import Severity, scan
from pif.cli import app, collect_pdfs
from pif.ml.cascade import split_segments

FIXTURES = Path(__file__).parent / "fixtures"  # generated by test_fixtures.py at import


def _tree(tmp_path: Path) -> Path:
    root = tmp_path / "docs"
    (root / "a" / "b").mkdir(parents=True)
    (root / ".hidden").mkdir()
    shutil.copy(FIXTURES / "clean.pdf", root / "top.pdf")
    shutil.copy(FIXTURES / "white_text.pdf", root / "a" / "b" / "Deep.PDF")
    shutil.copy(FIXTURES / "visible_injection.pdf", root / "a" / "mid.pdf")
    shutil.copy(FIXTURES / "clean.pdf", root / ".hidden" / "skip.pdf")
    (root / "a" / "notes.txt").write_text("not a pdf")
    return root


def test_collect_recursive(tmp_path: Path) -> None:
    root = _tree(tmp_path)
    names = [p.name for p in collect_pdfs([root])]
    assert sorted(names) == ["Deep.PDF", "mid.pdf", "top.pdf"]
    assert [p.name for p in collect_pdfs([root], recursive=False)] == ["top.pdf"]
    assert "skip.pdf" in [p.name for p in collect_pdfs([root], include_hidden=True)]
    # duplicates via overlapping arguments are scanned once
    assert len(collect_pdfs([root, root / "a", root / "top.pdf"])) == 3


@pytest.mark.parametrize("jobs", ["1", "3"])
def test_cli_directory_scan(tmp_path: Path, jobs: str) -> None:
    root = _tree(tmp_path)
    res = CliRunner().invoke(app, ["scan", str(root), "-f", "json", "-j", jobs, "--ml", "off", "--progress", "--fail-on", "never"])
    assert res.exit_code == 0, res.output
    out = res.stdout
    data = json.loads(out[out.index("[") :])
    by_name = {Path(r["path"]).name: r["max_severity"] for r in data}
    assert by_name == {"top.pdf": None, "Deep.PDF": "high", "mid.pdf": "medium"}


def test_split_segments_offsets() -> None:
    text = "Short. This is a longer sentence that goes on for a while. And another one here!"
    for seg in split_segments(text, offset=10):
        assert text[seg.start - 10 : seg.end - 10] == seg.text


